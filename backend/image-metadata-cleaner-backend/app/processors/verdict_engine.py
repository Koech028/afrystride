"""
Verdict engine - combines all processor results into a three-state verdict
"""
from typing import Dict, Any, List
from .base import AISignature


class VerdictEngine:
    """
    Determines the three-state verdict based on all processor results:
    - ai_signature_found: AI metadata signatures detected
    - no_ai_metadata_detected: Metadata exists but no AI signatures
    - metadata_missing_or_stripped: No metadata found at all
    """

    VERDICT_AI_FOUND = "ai_signature_found"
    VERDICT_NO_AI = "no_ai_metadata_detected"
    VERDICT_MISSING = "metadata_missing_or_stripped"

    def determine_verdict(
        self,
        all_metadata: Dict[str, Any],
        all_signatures: List[AISignature]
    ) -> str:
        """
        Determine the verdict based on metadata and signatures

        Args:
            all_metadata: Combined metadata from all processors
            all_signatures: All detected AI signatures

        Returns:
            Verdict string
        """
        # If we found AI signatures, that's the strongest verdict
        if all_signatures:
            return self.VERDICT_AI_FOUND

        # Check if any metadata was found at all
        has_metadata = self._has_any_metadata(all_metadata)

        if has_metadata:
            # Metadata exists but no AI signatures detected
            return self.VERDICT_NO_AI
        else:
            # No metadata found at all
            return self.VERDICT_MISSING

    def _has_any_metadata(self, metadata: Dict[str, Any]) -> bool:
        """Check if any meaningful metadata exists"""
        if not metadata:
            return False

        for section, data in metadata.items():
            if not data:
                continue

            # Handle different data types
            if isinstance(data, dict):
                # Check if dict has any non-empty values
                for key, value in data.items():
                    if value and str(value).strip():
                        # Skip trivial/technical fields
                        if key in ("srgb", "gamma", "transparency", "aspect", "interlace"):
                            continue
                        return True
            elif isinstance(data, list):
                if len(data) > 0:
                    return True
            elif data and str(data).strip():
                return True

        return False

    def get_verdict_description(self, verdict: str) -> str:
        """Get human-readable description for verdict"""
        descriptions = {
            self.VERDICT_AI_FOUND: (
                "This image contains metadata signatures indicating it was "
                "generated by an AI tool."
            ),
            self.VERDICT_NO_AI: (
                "Metadata is present, but no AI generation signatures were found. "
                "This does not prove the image is not AI-generated — metadata may "
                "have been stripped or the tool may not embed signatures."
            ),
            self.VERDICT_MISSING: (
                "No embedded metadata was found in this image. This could mean it "
                "was stripped, never had any, or the format doesn't support it. "
                "No determination can be made from metadata alone."
            ),
        }
        return descriptions.get(verdict, "Unknown verdict")
