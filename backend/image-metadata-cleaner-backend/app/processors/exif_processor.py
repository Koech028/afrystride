    # Midjourney job ID pattern
    MIDJOURNEY_PATTERN = ["job id", "job_id", "seed", "jobid"]

    @property
    def name(self) -> str:
        return "exif"

    def extract(self, image: PILImage.Image, raw_bytes: bytes) -> Dict[str, Any]:
        """Extract EXIF, XMP, and IPTC metadata"""
        result = {
            "exif": {},
            "xmp": {},
            "iptc": {},
        }

        # Extract EXIF via PIL
        exif_data = self._extract_exif_pil(image)
        if exif_data:
            result["exif"] = exif_data

        # Extract EXIF via piexif (more detailed)
        try:
            piexif_data = piexif.load(raw_bytes)
            if piexif_data:
                result["exif_piexif"] = self._format_piexif(piexif_data)
        except Exception:
            pass

        # Extract XMP
        xmp_data = self._extract_xmp(image)
        if xmp_data:
            result["xmp"] = xmp_data

        # Extract IPTC
        iptc_data = self._extract_iptc(image)
        if iptc_data:
            result["iptc"] = iptc_data

        return result

    def _extract_exif_pil(self, image: PILImage.Image) -> Dict[str, Any]:
        """Extract EXIF data using PIL"""
        exif = {}
        try:
            raw_exif = image._getexif()
            if raw_exif:
                for tag_id, value in raw_exif.items():
                    tag_name = TAGS.get(tag_id, f"Unknown({tag_id})")
                    # Convert bytes to string if needed
                    if isinstance(value, bytes):
                        try:
                            value = value.decode("utf-8", errors="ignore").strip("\x00")
                        except:
                            value = str(value)
                    # Handle tuples (like GPS coordinates)
                    elif isinstance(value, tuple):
                        value = str(value)
                    exif[tag_name] = str(value) if not isinstance(value, (int, float)) else value
        except Exception:
            pass
        return exif

    def _format_piexif(self, piexif_data: dict) -> Dict[str, Any]:
        """Format piexif data for readability"""
        formatted = {}
        for ifd_name, ifd_data in piexif_data.items():
            if ifd_name == "thumbnail" and ifd_data:
                formatted["thumbnail_present"] = True
                continue
            if not ifd_data:
                continue

            ifd_formatted = {}
            for tag_id, value in ifd_data.items():
                tag_name = piexif.TAGS.get(tag_id, {}).get("name", f"Tag_{tag_id}")
                if isinstance(value, bytes):
                    try:
                        value = value.decode("utf-8", errors="ignore").strip("\x00")
                    except:
                        value = str(value)
                ifd_formatted[tag_name] = str(value) if not isinstance(value, (int, float)) else value

            if ifd_formatted:
                formatted[ifd_name] = ifd_formatted

        return formatted

    def _extract_xmp(self, image: PILImage.Image) -> Dict[str, Any]:
        """Extract XMP metadata from image"""
        xmp = {}
        try:
            # XMP is typically in the info dict for PNG, or app13 for JPEG
            if hasattr(image, "info") and "xmp" in image.info:
                xmp_raw = image.info["xmp"]
                if isinstance(xmp_raw, bytes):
                    xmp_raw = xmp_raw.decode("utf-8", errors="ignore")
                xmp["raw_xml"] = xmp_raw[:2000]  # Truncate for readability

                # Try to parse key fields
                if "dc:title" in xmp_raw:
                    xmp["has_dublin_core"] = True
                if "xmpMM:History" in xmp_raw:
                    xmp["has_history"] = True
                if "photoshop:Credit" in xmp_raw:
                    xmp["has_photoshop"] = True

        except Exception:
            pass
        return xmp

    def _extract_iptc(self, image: PILImage.Image) -> Dict[str, Any]:
        """Extract IPTC metadata"""
        iptc = {}
        try:
            if hasattr(image, "info") and "photoshop" in image.info:
                iptc["photoshop_data_present"] = True
        except Exception:
            pass
        return iptc

    def detect_ai_signatures(self, metadata: Dict[str, Any]) -> List[AISignature]:
        """Detect AI generation signatures in EXIF/XMP/IPTC data"""
        signatures = []

        # Check all metadata sections
        all_text = json.dumps(metadata).lower()

        # Check EXIF fields
        exif_data = metadata.get("exif", {})
        piexif_data = metadata.get("exif_piexif", {})

        # Flatten piexif data for searching
        flat_exif = {}
        for section, data in piexif_data.items():
            if isinstance(data, dict):
                flat_exif.update(data)
        flat_exif.update(exif_data)

        # Check for known AI tool signatures
        for field_name, keywords in self.AI_TOOL_SIGNATURES.items():
            field_value = flat_exif.get(field_name, "").lower()
            if not field_value:
                continue

            for keyword in keywords:
                if keyword in field_value:
                    signatures.append(AISignature(
                        type=f"EXIF {field_name}",
                        detail=f"Field '{field_name}' contains '{keyword}': {field_value[:100]}",
                        confidence="high"
                    ))
                    break  # Only report once per field

        # Check for Midjourney job IDs
        for field_name, value in flat_exif.items():
            value_str = str(value).lower()
            for pattern in self.MIDJOURNEY_PATTERN:
                if pattern in value_str and ("midjourney" in all_text or len(str(value)) > 20):
                    signatures.append(AISignature(
                        type="Midjourney Job ID",
                        detail=f"Found in {field_name}: {str(value)[:100]}",
                        confidence="medium"
                    ))
                    break

        # Check XMP for AI indicators
        xmp_data = metadata.get("xmp", {})
        xmp_raw = str(xmp_data).lower()
        ai_xmp_indicators = [
            "generatedby", "ai.tool", "ai_tool", "synthetic",
            "digital_source_type", "trained_algorithmic_media",
        ]
        for indicator in ai_xmp_indicators:
            if indicator in xmp_raw:
                signatures.append(AISignature(
                    type="XMP AI Indicator",
                    detail=f"XMP contains '{indicator}'",
                    confidence="medium"
                ))
                break

        return signatures

    def strip(self, image: PILImage.Image, raw_bytes: bytes) -> bytes:
        """Strip EXIF and metadata from image"""
        output = io.BytesIO()

        # Create a clean copy - re-encode to ensure metadata removal
        clean_image = image.copy()

        # For JPEG: remove EXIF, ICC profile, etc.
        if image.format in ("JPEG", "JPG"):
            # Save without any extra info
            clean_image.save(
                output,
                format="JPEG",
                quality=95,
                optimize=True,
                exif=b"",
                icc_profile=None,
            )
        elif image.format == "PNG":
            # For PNG, we need to handle chunks separately
            # Save basic image without text chunks
            clean_image.save(
                output,
                format="PNG",
                optimize=True,
            )
        elif image.format == "WEBP":
            clean_image.save(
                output,
                format="WEBP",
                quality=95,
                exif=b"",
            )
        else:
            clean_image.save(output, format=image.format)

        return output.getvalue()
